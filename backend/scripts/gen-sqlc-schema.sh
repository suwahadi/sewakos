#!/usr/bin/env bash
# Regenerate db/schema.sql: the Up-only, concatenated view of db/migrations/*.sql
# that sqlc reads to build its catalog. Goose migration files interleave Up and
# Down SQL in one file (so a raw DROP TABLE in a Down block would otherwise empty
# sqlc's catalog if it read the whole file); this script strips everything but the
# Up sections, in migration order. Run it whenever a migration changes, before
# `go run github.com/sqlc-dev/sqlc/cmd/sqlc@<version> generate`.
set -euo pipefail
cd "$(dirname "$0")/.."

out="db/schema.sql"
{
  echo "-- Generated by scripts/gen-sqlc-schema.sh from db/migrations/*.sql. DO NOT EDIT."
  echo "-- Regenerate after changing a migration; see that script for why this exists."
  for f in db/migrations/*.sql; do
    awk '/^-- \+goose Up/{flag=1; next} /^-- \+goose Down/{flag=0} flag' "$f"
  done
} > "$out"
echo "Wrote $out"
